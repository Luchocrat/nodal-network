import type { Assessment } from "./scenario";

const sgn = (n: number) => (n < 0 ? `−${Math.abs(n)}` : `${n}`);

/**
 * Deterministic plain-language explanation built only from the assessment object.
 * Used when Gemma is unavailable or failed. No model, no network, no new facts.
 */
export function deterministicExplanation(a: Assessment): { heading: string; lines: string[] }[] {
  if (!a.valid) {
    return [
      { heading: "WHAT THE NUMBERS SAY", lines: ["The scenario inputs are invalid, so nothing was computed.", ...a.errors] },
      { heading: "WHAT WE DO NOT KNOW", lines: a.dataGaps.map((g) => `${g.label}: unknown.`) },
      { heading: "RECOMMENDED NEXT ACTION", lines: [a.action.text] },
    ];
  }
  const net = a.power.netPowerKw as number;
  const says: string[] = [
    `Simulated net power is ${net > 0 ? "+" : ""}${sgn(net)} kW (${a.power.formula}); status ${a.power.energyStatus.replace("_", " ")}.`,
  ];
  if (a.power.batteryRuntimeHours !== null) says.push(`With the optional simulated battery, the shortfall could be covered for about ${a.power.batteryRuntimeHours} h (${a.power.batteryRuntimeFormula ?? "kWh ÷ shortfall"}; ignores losses).`);
  if (a.selectedNode) says.push(`${a.selectedNode.id} carries an illustrative ${a.selectedNode.allocatedDemandKw} kW (${a.selectedNode.workloadSharePct}% of network demand). This is a CONCEPTUAL allocation, not a node measurement.`);
  const triggered = a.rules.filter((r) => r.status === "TRIGGERED").map((r) => r.id);
  says.push(`Rules triggered: ${triggered.join(", ")}.`);
  return [
    { heading: "WHAT THE NUMBERS SAY", lines: says },
    {
      heading: "WHAT WE DO NOT KNOW (UNCERTAINTY)",
      lines: [`Site ecological suitability is ${a.verdict.siteSuitability.toLowerCase()} and deployment readiness is ${a.verdict.deploymentReadiness.replace("_", " ").toLowerCase()}, whatever the power balance.`, ...a.dataGaps.map((g) => `${g.label}: UNKNOWN.`)],
    },
    { heading: "RECOMMENDED NEXT ACTION", lines: [`${a.action.id}: ${a.action.text}`] },
    { heading: "LIMITS OF THIS EXPLANATION", lines: ["Generated by fixed NODAL rules from simulated inputs. It is not an observation and does not certify ecological or engineering safety."] },
  ];
}
